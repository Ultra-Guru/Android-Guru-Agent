package com.apex.agent.platform.terminal.searxng

import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File

/**
 * ═══ M2：settings.yml 生成与幂等写入（SearXNG Local Search Spec v1.0 §7）═══
 *
 * 配置语义（Spec §7 表）：
 *
 * | 段          | 字段            | 值/规则                                        |
 * |-------------|-----------------|-----------------------------------------------|
 * | general     | instance_name   | guru-local                                     |
 * | general     | debug           | false                                          |
 * | server      | secret_key      | 意图存储生成并复用（[SearxngIntentPort.secretKey]）|
 * | server      | bind_address    | 127.0.0.1（禁止 0.0.0.0 —— 本地单实例）         |
 * | server      | port            | 8888（意图存储）                                |
 * | server      | limiter         | false（本地单用户，避免误限流）                  |
 * | server      | public_instance | false                                          |
 * | search      | formats         | [html, json]（缺 json 则 JSON API 403）          |
 * | search      | safe_search     | 0                                              |
 * | engines     | keep_only       | 用户名单（目录 6 选，默认 google/bing/ddg）       |
 * | engines     | disabled        | 名单内 false                                    |
 *
 * 引擎过滤实现注记：SearXNG 的 `use_default_settings.engines.keep_only` 官方语义
 * —— 从内置默认引擎表中**只保留**名单所列引擎。这比逐个 `disabled: true` 枚举
 * 261 个引擎稳健（新版本引擎表变动不破坏配置），且天然满足 AC11（仅 wikipedia
 * → 结果只来自 wikipedia）。
 *
 * 写入方式：host 侧直写（rootfs 即 host 目录 —— 与 [SearxngInstaller] 的文件
 * 检查同一物理事实源），原子写（.tmp → rename），幂等（内容变化才落盘）。
 * 修改运行中配置需重启生效 —— 引擎变更的「写 + 重启」编排由 coordinator 承担
 * （Spec §6 setEngines 契约），本类只管文件。
 */
class SearxngSettingsWriter(
    private val commands: SearxngCommandPort,
    private val intent: SearxngIntentPort,
    /**
     * 文件写调度器（可注入 —— JVM 测试注入 TestDispatcher 保持虚拟时间确定性：
     * Dispatchers.IO 是真线程池，runTest 的 runCurrent/advanceTimeBy 等不到它，
     * 后台链会停在挂起点上让断言读到中间态）。
     */
    private val ioDispatcher: CoroutineDispatcher = Dispatchers.IO
) {

    /** 渲染 settings.yml 全文（纯函数 —— 单测逐行断言）。 */
    fun render(): String = buildString {
        append("# Generated by Android-Guru-Agent (SearXNG local search) — do not edit.\n")
        append("use_default_settings:\n")
        append("  engines:\n")
        append("    keep_only:\n")
        selectedEngines().forEach { engine ->
            append("      - $engine\n")
        }
        append("general:\n")
        append("  instance_name: guru-local\n")
        append("  debug: false\n")
        append("server:\n")
        append("  secret_key: ${intent.secretKey()}\n")
        append("  bind_address: ${SearxngContract.BIND_ADDRESS}\n")
        append("  port: ${intent.port()}\n")
        append("  limiter: false\n")
        append("  public_instance: false\n")
        append("search:\n")
        append("  formats:\n")
        append("    - html\n")
        append("    - json\n")
        append("  safe_search: 0\n")
        append("engines:\n")
        selectedEngines().forEach { engine ->
            append("  - name: $engine\n")
            append("    disabled: false\n")
        }
    }

    /**
     * 当前生效引擎名单（公开只读视图 —— UI 展示「127.0.0.1:8888 · Google/Bing/DDG」
     * 副标题用，Spec §11）。非法值（不在目录内的历史残留）诚实过滤。
     */
    fun currentEngines(): Set<String> = selectedEngines().toSet()

    /**
     * 幂等写入：目标不存在 / 内容变化 → 原子写；内容一致 → no-op（避免无谓的
     * mtime 变化触发守护进程重启）。失败携带结构化 reason。
     */
    suspend fun ensureConfig(): Result<Unit> = try {
        val rootfs = commands.rootfsDir()
            ?: return Result.failure(RuntimeException("ubuntu not ready — rootfs unavailable"))
        val target = SearxngScripts.hostSettingsFile(rootfs)
        val content = render()
        val unchanged = target.isFile && runCatching {
            target.readText() == content
        }.getOrDefault(false)
        if (!unchanged) {
            withContext(ioDispatcher) {
                target.parentFile?.mkdirs()
                val tmp = File(target.parentFile, target.name + ".tmp")
                tmp.writeText(content)
                if (!tmp.renameTo(target)) {
                    tmp.delete()
                    throw java.io.IOException("atomic rename failed: ${target.absolutePath}")
                }
            }
        }
        Result.success(Unit)
    } catch (e: CancellationException) {
        throw e
    } catch (e: Exception) {
        Result.failure(RuntimeException(
            "build failed — settings.yml: ${e.message ?: e::class.simpleName}"
        ))
    }

    /** 名单归一：空/全空 → 默认引擎；仅保留目录内合法项；稳定排序（输出确定）。 */
    private fun selectedEngines(): List<String> {
        val legal = intent.engines()
            .filter { id -> SEARXNG_ENGINE_CATALOG.any { it.id == id } }
        return (legal.ifEmpty { SEARXNG_DEFAULT_ENGINES.toList() }).sorted()
    }
}
